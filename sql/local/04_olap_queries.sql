-- OLAP queries for the local DuckDB galaxy schema.
-- Run after scripts/build_local.py has populated mart.*.

-- 1. ROLL-UP: deposits by year, quarter, and month.
SELECT dd.YEAR,
    dd.QUARTER,
    dd.MONTH_NAME,
    SUM(ft.AMOUNT) AS TOTAL_DEPOSITS
FROM FACT_TRANSACTIONS ft
JOIN DIM_DATE dd ON ft.DATE_ID = dd.DATE_ID
WHERE ft.TRANSACTION_TYPE = 'Deposit'
GROUP BY ROLLUP (dd.YEAR, dd.QUARTER, dd.MONTH_NAME)
ORDER BY dd.YEAR NULLS LAST,
    dd.QUARTER NULLS LAST,
    dd.MONTH_NAME NULLS LAST;

-- 2. DRILL-DOWN: region -> city -> branch.
SELECT db.REGION,
    db.CITY,
    db.BRANCH_NAME,
    COUNT(*) AS TXN_COUNT,
    SUM(ft.AMOUNT) AS TXN_TOTAL
FROM FACT_TRANSACTIONS ft
JOIN DIM_BRANCH db ON ft.BRANCH_ID = db.BRANCH_ID
GROUP BY db.REGION, db.CITY, db.BRANCH_NAME
ORDER BY db.REGION, db.CITY, db.BRANCH_NAME;

-- 3. SLICE: loan portfolio for Home loans.
SELECT dlt.LOAN_TYPE_NAME,
    db.BRANCH_NAME,
    COUNT(*) AS LOAN_COUNT,
    SUM(fl.AMOUNT) AS TOTAL_DISBURSED
FROM FACT_LOANS fl
JOIN DIM_LOAN_TYPE dlt ON fl.LOAN_TYPE_ID = dlt.LOAN_TYPE_ID
JOIN DIM_BRANCH db ON fl.BRANCH_ID = db.BRANCH_ID
WHERE dlt.LOAN_TYPE_NAME = 'Unspecified'
GROUP BY dlt.LOAN_TYPE_NAME, db.BRANCH_NAME
ORDER BY TOTAL_DISBURSED DESC;

-- 4. DICE: Q1 transactions in the South region.
SELECT db.REGION,
    db.BRANCH_NAME,
    dd.QUARTER,
    ft.TRANSACTION_TYPE,
    SUM(ft.AMOUNT) AS TOTAL_AMOUNT
FROM FACT_TRANSACTIONS ft
JOIN DIM_BRANCH db ON ft.BRANCH_ID = db.BRANCH_ID
JOIN DIM_DATE dd ON ft.DATE_ID = dd.DATE_ID
WHERE dd.QUARTER = 1
    AND db.REGION LIKE 'south%'
GROUP BY db.REGION, db.BRANCH_NAME, dd.QUARTER, ft.TRANSACTION_TYPE
ORDER BY db.BRANCH_NAME;

-- 5. CUBE: every combination of region and transaction type.
SELECT db.REGION,
    ft.TRANSACTION_TYPE,
    SUM(ft.AMOUNT) AS TOTAL_AMOUNT,
    COUNT(*) AS TXN_COUNT
FROM FACT_TRANSACTIONS ft
JOIN DIM_BRANCH db ON ft.BRANCH_ID = db.BRANCH_ID
GROUP BY CUBE (db.REGION, ft.TRANSACTION_TYPE)
ORDER BY db.REGION NULLS LAST,
    ft.TRANSACTION_TYPE NULLS LAST;

-- 6. Top 10 branches by deposits.
SELECT db.BRANCH_NAME,
    db.CITY,
    SUM(CASE WHEN ft.TRANSACTION_TYPE = 'Deposit' THEN ft.AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS
FROM FACT_TRANSACTIONS ft
JOIN DIM_BRANCH db ON ft.BRANCH_ID = db.BRANCH_ID
GROUP BY db.BRANCH_NAME, db.CITY
ORDER BY TOTAL_DEPOSITS DESC
LIMIT 10;

-- 7. Loan distribution by loan type.
SELECT dlt.LOAN_TYPE_NAME,
    COUNT(*) AS LOAN_COUNT,
    SUM(fl.AMOUNT) AS TOTAL_AMOUNT,
    ROUND(AVG(fl.TENURE_MONTHS), 1) AS AVG_TENURE_MONTHS
FROM FACT_LOANS fl
JOIN DIM_LOAN_TYPE dlt ON fl.LOAN_TYPE_ID = dlt.LOAN_TYPE_ID
GROUP BY dlt.LOAN_TYPE_NAME
ORDER BY TOTAL_AMOUNT DESC;

-- 8. Customer transaction behavior by segment and age group.
SELECT dc.CUSTOMER_SEGMENT,
    dc.AGE_GROUP,
    COUNT(DISTINCT dc.CUSTOMER_ID) AS CUSTOMERS,
    ROUND(AVG(ft.AMOUNT), 2) AS AVG_TXN_AMOUNT
FROM FACT_TRANSACTIONS ft
JOIN DIM_ACCOUNT da ON ft.ACCOUNT_ID = da.ACCOUNT_ID
JOIN DIM_CUSTOMER dc ON da.CUSTOMER_ID = dc.CUSTOMER_ID
GROUP BY dc.CUSTOMER_SEGMENT, dc.AGE_GROUP
ORDER BY dc.CUSTOMER_SEGMENT, dc.AGE_GROUP;

-- 9. Monthly transaction totals by transaction type.
SELECT dd.YEAR,
    dd.MONTH,
    dd.MONTH_NAME,
    ft.TRANSACTION_TYPE,
    SUM(ft.AMOUNT) AS TOTAL_AMOUNT
FROM FACT_TRANSACTIONS ft
JOIN DIM_DATE dd ON ft.DATE_ID = dd.DATE_ID
GROUP BY dd.YEAR, dd.MONTH, dd.MONTH_NAME, ft.TRANSACTION_TYPE
ORDER BY dd.YEAR, dd.MONTH, ft.TRANSACTION_TYPE;

-- 10. Monthly net cash flow: deposits minus withdrawals.
SELECT dd.YEAR,
    dd.MONTH,
    dd.MONTH_NAME,
    SUM(CASE WHEN ft.TRANSACTION_TYPE = 'Deposit' THEN ft.AMOUNT ELSE 0 END)
        - SUM(CASE WHEN ft.TRANSACTION_TYPE = 'Withdrawal' THEN ft.AMOUNT ELSE 0 END)
        AS NET_CASH_FLOW
FROM FACT_TRANSACTIONS ft
JOIN DIM_DATE dd ON ft.DATE_ID = dd.DATE_ID
GROUP BY dd.YEAR, dd.MONTH, dd.MONTH_NAME
ORDER BY dd.YEAR, dd.MONTH;

-- 11. Loan status breakdown by branch.
SELECT db.BRANCH_NAME,
    fl.STATUS,
    COUNT(*) AS LOAN_COUNT,
    SUM(fl.AMOUNT) AS TOTAL_AMOUNT
FROM FACT_LOANS fl
JOIN DIM_BRANCH db ON fl.BRANCH_ID = db.BRANCH_ID
GROUP BY db.BRANCH_NAME, fl.STATUS
ORDER BY db.BRANCH_NAME, fl.STATUS;

-- 12. Weekday versus weekend transaction activity.
SELECT dd.IS_WEEKEND,
    ft.TRANSACTION_TYPE,
    COUNT(*) AS TXN_COUNT,
    ROUND(AVG(ft.AMOUNT), 2) AS AVG_AMOUNT
FROM FACT_TRANSACTIONS ft
JOIN DIM_DATE dd ON ft.DATE_ID = dd.DATE_ID
GROUP BY dd.IS_WEEKEND, ft.TRANSACTION_TYPE
ORDER BY dd.IS_WEEKEND, ft.TRANSACTION_TYPE;

-- 13. Overall loan default rate.
SELECT COUNT(*) AS TOTAL_LOANS,
    COUNT_IF(STATUS = 'Defaulted') AS DEFAULTED_LOANS,
    ROUND(100.0 * COUNT_IF(STATUS = 'Defaulted') / NULLIF(COUNT(*), 0), 2)
        AS DEFAULT_RATE_PERCENT
FROM FACT_LOANS;

-- 14. Loan default rate by branch.
SELECT db.BRANCH_NAME,
    COUNT(*) AS TOTAL_LOANS,
    COUNT_IF(fl.STATUS = 'Defaulted') AS DEFAULTED_LOANS,
    ROUND(100.0 * COUNT_IF(fl.STATUS = 'Defaulted') / NULLIF(COUNT(*), 0), 2)
        AS DEFAULT_RATE_PERCENT
FROM FACT_LOANS fl
JOIN DIM_BRANCH db ON fl.BRANCH_ID = db.BRANCH_ID
GROUP BY db.BRANCH_NAME
ORDER BY DEFAULT_RATE_PERCENT DESC;
