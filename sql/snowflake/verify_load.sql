-- Run after scripts/upload_to_snowflake.py finishes.
USE DATABASE LOAN_DEFAULT_DW;

SHOW SCHEMAS IN DATABASE LOAN_DEFAULT_DW;
SHOW TABLES IN SCHEMA LOAN_DEFAULT_DW.RAW;
SHOW TABLES IN SCHEMA LOAN_DEFAULT_DW.MART;

SELECT 'RAW_CLIENT' AS table_name, COUNT(*) AS row_count
FROM LOAN_DEFAULT_DW.RAW.RAW_CLIENT
UNION ALL SELECT 'RAW_ACCOUNT', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_ACCOUNT
UNION ALL SELECT 'RAW_DISP', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_DISP
UNION ALL SELECT 'RAW_LOAN', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_LOAN
UNION ALL SELECT 'RAW_TRANS', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_TRANS
UNION ALL SELECT 'MART_LOAN_FEATURES', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_LOAN_FEATURES
UNION ALL SELECT 'MART_MODEL_SCORES', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_MODEL_SCORES
UNION ALL SELECT 'MART_LOAN_SEGMENTS', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_LOAN_SEGMENTS
UNION ALL SELECT 'MART_LOAN_RISK', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_LOAN_RISK
UNION ALL SELECT 'MART_CLUSTER_LABELS', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_CLUSTER_LABELS
UNION ALL SELECT 'MART_CLUSTERING_COMPARISON', COUNT(*) FROM LOAN_DEFAULT_DW.MART.MART_CLUSTERING_COMPARISON
UNION ALL SELECT 'DIM_DATE', COUNT(*) FROM LOAN_DEFAULT_DW.MART.DIM_DATE
UNION ALL SELECT 'DIM_BRANCH', COUNT(*) FROM LOAN_DEFAULT_DW.MART.DIM_BRANCH
UNION ALL SELECT 'DIM_CUSTOMER', COUNT(*) FROM LOAN_DEFAULT_DW.MART.DIM_CUSTOMER
UNION ALL SELECT 'DIM_ACCOUNT', COUNT(*) FROM LOAN_DEFAULT_DW.MART.DIM_ACCOUNT
UNION ALL SELECT 'DIM_LOAN_TYPE', COUNT(*) FROM LOAN_DEFAULT_DW.MART.DIM_LOAN_TYPE
UNION ALL SELECT 'FACT_LOANS', COUNT(*) FROM LOAN_DEFAULT_DW.MART.FACT_LOANS
UNION ALL SELECT 'FACT_TRANSACTIONS', COUNT(*) FROM LOAN_DEFAULT_DW.MART.FACT_TRANSACTIONS
ORDER BY table_name;

-- Expected:
-- RAW_CLIENT 5369, RAW_ACCOUNT 4500, RAW_DISP 5369, RAW_LOAN 682,
-- RAW_TRANS 1056320, MART_LOAN_FEATURES 682, MART_MODEL_SCORES 682,
-- MART_LOAN_SEGMENTS 682, MART_LOAN_RISK 682, MART_CLUSTER_LABELS 682,
-- MART_CLUSTERING_COMPARISON 4, DIM_DATE 2191, DIM_BRANCH 77,
-- DIM_CUSTOMER 5369, DIM_ACCOUNT 4500, DIM_LOAN_TYPE 1, FACT_LOANS 682,
-- FACT_TRANSACTIONS 1056320.

SELECT * FROM LOAN_DEFAULT_DW.MART.V_LOAN_PERF LIMIT 10;
SELECT * FROM LOAN_DEFAULT_DW.MART.V_TRANS_MONTHLY LIMIT 10;
SELECT method, parameter, n_clusters, silhouette, davies_bouldin,
       calinski_harabasz, coverage, noise_share, stability_ari_mean,
       role, recommended
FROM LOAN_DEFAULT_DW.MART.MART_CLUSTERING_COMPARISON
ORDER BY recommended DESC, silhouette DESC;
