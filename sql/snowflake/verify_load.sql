USE DATABASE LOAN_DEFAULT_DW;

SELECT 'RAW_CLIENT' AS table_name, COUNT(*) AS rows
FROM LOAN_DEFAULT_DW.RAW.RAW_CLIENT
UNION ALL SELECT 'RAW_ACCOUNT', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_ACCOUNT
UNION ALL SELECT 'RAW_DISP', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_DISP
UNION ALL SELECT 'RAW_LOAN', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_LOAN
UNION ALL SELECT 'RAW_TRANS', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.RAW_TRANS
UNION ALL SELECT 'MART_LOAN_FEATURES', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.MART_LOAN_FEATURES
UNION ALL SELECT 'MART_MODEL_SCORES', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.MART_MODEL_SCORES
UNION ALL SELECT 'MART_LOAN_SEGMENTS', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.MART_LOAN_SEGMENTS
UNION ALL SELECT 'MART_LOAN_RISK', COUNT(*) FROM LOAN_DEFAULT_DW.RAW.MART_LOAN_RISK
ORDER BY table_name;

