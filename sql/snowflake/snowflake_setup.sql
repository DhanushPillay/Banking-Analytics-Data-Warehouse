CREATE OR REPLACE VIEW VW_MODEL_PERFORMANCE AS
SELECT
  MODEL,
  SETTING,
  VARIANT,
  CV_F1_MEAN,
  CV_F1_STD,
  CV_AP_MEAN,
  CV_AUC_MEAN,
  RANK() OVER (PARTITION BY VARIANT ORDER BY CV_F1_MEAN DESC) AS F1_RANK
FROM MODEL_CV_COMPARISON;

-- Semantic view for Power BI: one row per loan with customer, branch,
-- loan type, and calendar attributes already joined.
CREATE OR REPLACE VIEW VW_LOAN_ANALYTICS AS
SELECT
  f.LOAN_ID,
  f.AMOUNT,
  f.INTEREST_RATE,
  f.TENURE_MONTHS,
  f.STATUS AS LOAN_STATUS,
  c.CUSTOMER_ID,
  c.GENDER,
  c.AGE,
  c.AGE_GROUP,
  c.CITY AS CUSTOMER_CITY,
  c.CUSTOMER_SEGMENT,
  b.BRANCH_ID,
  b.BRANCH_NAME,
  b.REGION,
  b.BRANCH_TYPE,
  lt.LOAN_TYPE_NAME,
  d.FULL_DATE AS LOAN_DATE,
  d.MONTH_NAME,
  d.QUARTER,
  d.YEAR
FROM FACT_LOANS f
LEFT JOIN DIM_CUSTOMER c ON c.CUSTOMER_ID = f.CUSTOMER_ID
LEFT JOIN DIM_BRANCH b ON b.BRANCH_ID = f.BRANCH_ID
LEFT JOIN DIM_LOAN_TYPE lt ON lt.LOAN_TYPE_ID = f.LOAN_TYPE_ID
LEFT JOIN DIM_DATE d ON d.DATE_ID = f.DATE_ID;

-- Validation checks before connecting Power BI.
SELECT 'DIM_ACCOUNT' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM DIM_ACCOUNT
UNION ALL SELECT 'DIM_BRANCH', COUNT(*) FROM DIM_BRANCH
UNION ALL SELECT 'DIM_CUSTOMER', COUNT(*) FROM DIM_CUSTOMER
UNION ALL SELECT 'DIM_DATE', COUNT(*) FROM DIM_DATE
UNION ALL SELECT 'DIM_LOAN_TYPE', COUNT(*) FROM DIM_LOAN_TYPE
UNION ALL SELECT 'FACT_LOANS', COUNT(*) FROM FACT_LOANS
UNION ALL SELECT 'FACT_TRANSACTIONS', COUNT(*) FROM FACT_TRANSACTIONS;

SELECT LOAN_STATUS, COUNT(*) AS LOAN_COUNT
FROM VW_LOAN_ANALYTICS
GROUP BY LOAN_STATUS
ORDER BY LOAN_STATUS;